import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { createAgentSession, DefaultResourceLoader, ModelRuntime, SettingsManager, SessionManager } from '@earendil-works/pi-coding-agent';
import { packed, isolated, captures } from './helpers.mjs';

test('real SDK loads packed resources and restores mode on tree navigation and reload', { timeout: 30000 }, async t => {
  const artifact = packed(); t.after(() => rmSync(artifact.dir, { recursive: true, force: true }));
  const dir = join(artifact.dir, 'sdk'); mkdirSync(dir);
  const iso = isolated(dir, artifact.packageRoot);
  const oldEnv = { ...process.env };
  for (const key of Object.keys(process.env)) delete process.env[key];
  Object.assign(process.env, iso.env);
  t.after(() => { for (const key of Object.keys(process.env)) delete process.env[key]; Object.assign(process.env, oldEnv); });
  const settingsManager = SettingsManager.create(dir, iso.agentDir);
  const modelRuntime = await ModelRuntime.create({ authPath: join(iso.agentDir, 'auth.json'), modelsPath: join(iso.agentDir, 'models.json'), refreshOnCreate: false, allowModelNetwork: false });
  const loader = new DefaultResourceLoader({ cwd: dir, agentDir: iso.agentDir, settingsManager, noContextFiles: true, noThemes: true, noPromptTemplates: true, additionalExtensionPaths: [join(artifact.packageRoot, 'tests/fixtures/provider.ts'), join(artifact.packageRoot, 'tests/fixtures/prototype.ts')] });
  await loader.reload();
  assert.deepEqual(loader.getExtensions().errors, []);
  assert.equal(loader.getSkills().skills.length, 58);
  const manager = SessionManager.create(dir, join(iso.agentDir, 'sessions'));
  const { session } = await createAgentSession({ cwd: dir, agentDir: iso.agentDir, resourceLoader: loader, modelRuntime, settingsManager, sessionManager: manager });
  t.after(() => session.dispose());
  const extensionErrors = [];
  await session.bindExtensions({ onError: error => extensionErrors.push(error) });
  const scripted = modelRuntime.getModel('mstack-test', 'script/model');
  assert.ok(scripted);
  await session.setModel(scripted);
  session.setThinkingLevel('off');
  await session.prompt('/poteto-mode');
  const on = manager.getLeafId();
  await session.prompt('SDK_ON');
  assert.match(captures(iso.env).at(-1).system, /<pi-mstack-mode>/);
  await session.prompt('/poteto-mode off');
  await session.prompt('SDK_OFF');
  assert.doesNotMatch(captures(iso.env).at(-1).system, /<pi-mstack-mode>/);
  await session.navigateTree(on, { summarize: false });
  await session.prompt('SDK_TREE_ON');
  assert.match(captures(iso.env).at(-1).system, /<pi-mstack-mode>/);
  await session.reload();
  await session.prompt('SDK_RELOAD_ON');
  assert.match(captures(iso.env).at(-1).system, /<pi-mstack-mode>/);
  const wake = new Promise(resolve => { const off = session.subscribe(e => { if (e.type === 'agent_settled') { off(); resolve(); } }); });
  await session.prompt('/test-wake'); await wake;
  assert.match(captures(iso.env).at(-1).system, /<pi-mstack-role-data>/);
  assert.match(JSON.stringify(captures(iso.env).at(-1).messages), /CUSTOM_WAKE/);
  mkdirSync(join(iso.agentDir, 'pstack'), { recursive: true });
  for (const provider of ['team/custom', 'https://example.test/v1']) {
    const custom = modelRuntime.getModel(provider, 'script/model');
    assert.ok(custom);
    await session.setModel(custom);
    session.setThinkingLevel('off');
    writeFileSync(join(iso.agentDir, 'pstack/models.json'), JSON.stringify({ version: 'pi-mstack/1', roles: { 'how explorer': `${provider}/script/model:off`, 'how explainer': 'missing/provider/model:off' } }));
    await session.prompt('SDK_CUSTOM_PROVIDER');
    const system = captures(iso.env).at(-1).system;
    assert.ok(system.includes(`how explorer: ${provider}/script/model:off [registry-valid;`));
    assert.ok(system.includes(`bug-fix: ${provider}/script/model:off [registry-valid;`));
    assert.match(system, /how explainer: missing\/provider\/model:off \[BLOCKED, unavailable/);
  }
  writeFileSync(join(iso.agentDir, 'pstack/models.json'), '{}');
  await session.prompt('SDK_INVALID_CONFIG');
  assert.match(captures(iso.env).at(-1).system, /Configuration blocked/);
  assert.deepEqual(extensionErrors, []);
});
